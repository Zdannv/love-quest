export const fxKey = (e) => e.replace(/\uFE0F/g, '');
export const fxSrc = (e) => { const h = FX[fxKey(e)]; return h ? `/img/fx/${h}.webp` : null; };

// Ganti emoji di teks halaman jadi gambar 3D (kayak twemoji), termasuk yang muncul belakangan.
const RE = /(?:\p{Extended_Pictographic}|\p{Regional_Indicator}{2})(?:\uFE0F|\u20E3|[\u{1F3FB}-\u{1F3FF}]|\u200D\p{Extended_Pictographic}\uFE0F?)*/gu;
const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'OPTION', 'SELECT', 'TITLE', 'NOSCRIPT', 'CANVAS']);
function swapText(node) {
  const t = node.nodeValue;
  if (!t || !RE.test(t)) return;
  RE.lastIndex = 0;
  const frag = document.createDocumentFragment();
  let last = 0, hit = false;
  for (const m of t.matchAll(RE)) {
    const src = fxSrc(m[0]);
    if (!src) continue;
    hit = true;
    if (m.index > last) frag.append(t.slice(last, m.index));
    const img = document.createElement('img');
    img.className = 'fx'; img.src = src; img.alt = m[0]; img.draggable = false; img.decoding = 'async';
    frag.append(img);
    last = m.index + m[0].length;
  }
  if (!hit) return;
  if (last < t.length) frag.append(t.slice(last));
  node.replaceWith(frag);
}
function okParent(el) {
  for (let p = el; p && p !== document.body; p = p.parentElement) {
    if (SKIP.has(p.tagName) || p.isContentEditable || p.hasAttribute?.('data-nofx')) return false;
  }
  return true;
}
export function fxScan(root) {
  if (!root) return;
  if (root.nodeType === 3) { if (root.parentElement && okParent(root.parentElement)) swapText(root); return; }
  if (root.nodeType !== 1 || !okParent(root)) return;
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: (n) => (okParent(n.parentElement) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT) });
  const list = []; while (w.nextNode()) list.push(w.currentNode);
  list.forEach(swapText);
}
// Muat semua ikon pelan-pelan di belakang layar (sekali aja, abis itu kesimpen di HP)
function warmUp() {
  const list = [...new Set(Object.values(FX))];
  let i = 0;
  const next = () => { if (i >= list.length) return; const img = new Image(); img.onload = img.onerror = next; img.src = `/img/fx/${list[i++]}.webp`; };
  for (let k = 0; k < 6; k++) next();
}
export function fxWatch() {
  fxScan(document.body);
  setTimeout(() => (window.requestIdleCallback || setTimeout)(warmUp), 2500);
  new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') fxScan(m.target);
      else m.addedNodes.forEach(fxScan);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true });
}
